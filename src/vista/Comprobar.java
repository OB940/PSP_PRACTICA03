    public void refrescar() {
        Cliente c = lista.clienteActual();

        if (c == null) {
            labelPosicion.setText("NO HAY CLIENTES");
            labNumero.setText("-");
            labNombre.setText("-");
            labPuntos.setText("-");
            labFechaNac.setText("-");
        } else {
            labelPosicion.setText("CLIENTE " + (lista.getiCliente() + 1) + " DE " + lista.size());
            labNumero.setText(String.valueOf(c.getNumero()));
            labNombre.setText(c.getNombre());
            labPuntos.setText(String.valueOf(c.getPuntos()));
            labFechaNac.setText(c.getFechaNacimiento().format(ControlErrores.FORMATO_FECHA));
        }

        boolean hay = !lista.esVacia();
        bPrimero.setEnabled(hay && !lista.esPrimero());
        bAnterior.setEnabled(hay && !lista.esPrimero());
        bSiguiente.setEnabled(hay && !lista.esUltimo());
        bUltimo.setEnabled(hay && !lista.esUltimo());
        bEliminar.setEnabled(hay);
    }

