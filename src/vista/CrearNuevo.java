    private void bGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bGuardarActionPerformed
        // 1) VALIDAR (ControlErrores devuelve null si el campo está bien)
        String error = ControlErrores.validarNumero(txtNumero.getText());
        if (error == null) error = ControlErrores.validarPuntos(txtPuntos.getText());
        if (error == null) error = ControlErrores.validarFecha(txtFecha.getText());
        if (error == null && txtNombre.getText().isBlank()) error = "ERROR. EL NOMBRE NO PUEDE ESTAR VACÍO.";
        if (error == null && lista.existeNumero(Integer.parseInt(txtNumero.getText().trim()))) {
            error = "ERROR. YA EXISTE UN CLIENTE CON ESE NÚMERO.";
        }

        if (error != null) {
            labelError.setForeground(Color.RED);
            labelError.setText(error);
            return;
        }

        // 2) CREAR EL CLIENTE Y AÑADIRLO
        int numero = Integer.parseInt(txtNumero.getText().trim());
        String nombre = txtNombre.getText().trim();
        float puntos = Float.parseFloat(txtPuntos.getText().trim().replace(',', '.'));
        LocalDate fecha = LocalDate.parse(txtFecha.getText().trim(), ControlErrores.FORMATO_FECHA);

        lista.añadirCliente(new Cliente(numero, nombre, puntos, fecha));

        limpiar();
        labelError.setForeground(new Color(0, 128, 0));
        labelError.setText("CLIENTE " + numero + " AÑADIDO CORRECTAMENTE.");
    }//GEN-LAST:event_bGuardarActionPerformed

